// provision — T-2/T-3/T-4 (program board tooling lane; ticket
// 20260721_setup_and_doctor_verbs; ST-CLI-1). The missing VEHICLE: emit the
// infrastructure artifacts the boot gates enforce, generated FROM the
// enforcing registry so the artifact and the gate cannot drift.
//
// The verb is `provision`, NOT `setup` (ticket §6.1, DECIDED): quota.Setup is
// the library's own entry point and the collision would land in the docs.
//
// provision NEVER creates cloud resources — emit-and-let-them-apply (the D-3
// rule auto-create follows). `--local` creates ONE local Docker container,
// loudly, and only when asked.
